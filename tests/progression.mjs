import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const store=new Map();
const localStorage={getItem:k=>store.get(k)??null,setItem:(k,v)=>store.set(k,v)};
const module={exports:{}};
const source=ts.transpileModule(fs.readFileSync('lib/learning.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
vm.runInNewContext(source,{module,exports:module.exports,localStorage,window:{},console});
const {emptyProgress,loadProgress,saveProgress,completeLesson,lessonAccess,prerequisiteFor,nextIncomplete}=module.exports;
const lessons=[{id:'un'},{id:'deux'},{id:'trois'}],subject='mathematiques';
let p=structuredClone(emptyProgress);
assert.equal(lessonAccess(p,subject,lessons,'un').unlocked,true);
assert.equal(lessonAccess(p,subject,lessons,'deux').unlocked,false);
assert.equal(lessonAccess(p,subject,lessons,'trois').unlocked,false);
assert.equal(prerequisiteFor(p,subject,lessons,'trois').id,'un');
p=completeLesson(p,subject,'un');
assert.equal(lessonAccess(p,subject,lessons,'un').completed,true);
assert.equal(lessonAccess(p,subject,lessons,'un').unlocked,true,'validated lessons remain replayable');
assert.equal(lessonAccess(p,subject,lessons,'deux').unlocked,true,'next lesson unlocks');
assert.equal(lessonAccess(p,subject,lessons,'trois').unlocked,false);
assert.equal(nextIncomplete(p,subject,lessons).id,'deux');
saveProgress(p);
const restored=loadProgress();
assert.equal(lessonAccess(restored,subject,lessons,'deux').unlocked,true,'reload preserves unlock');
assert.equal(lessonAccess(restored,subject,lessons,'trois').unlocked,false);
const before=p.completed.length;
p=completeLesson(p,subject,'un');
assert.equal(p.completed.length,before,'replay does not duplicate completion');
p=completeLesson(p,subject,'deux');
assert.equal(lessonAccess(p,subject,lessons,'trois').unlocked,true);
assert.equal(lessonAccess(p,subject,lessons,'unknown').unlocked,false);
assert.equal(lessonAccess(p,'physique-chimie',lessons,'deux').unlocked,false,'subject isolation');
console.log('Progression: 13 assertions de verrouillage, reprise et révision validées');
